import { expect } from "chai";
import sinon from "sinon";
import { JSDOM } from "jsdom";
import SplittermondItem from "module/item/item";
import SplittermondItemSheet from "module/item/sheets/item-sheet";
import SplittermondItemEffectsSheet from "module/item/sheets/item-effects-sheet";
import { SplittermondActiveEffect } from "module/activeEffect";
import { foundryApi } from "module/api/foundryApi";

describe("Item sheet tabs after active effect drops", () => {
    const sandbox = sinon.createSandbox();
    const effectTypes = ["modifier", "autoGenerated"] as const;
    beforeEach(() => sandbox.stub(foundryApi, "localize").callsFake((key) => key));
    afterEach(() => sandbox.restore());

    function prepareDrop(type: (typeof effectTypes)[number]) {
        const item = sandbox.createStubInstance(SplittermondItem);
        item.type = "weapon";
        const sheet = new SplittermondItemEffectsSheet({ document: item });
        Object.defineProperty(sheet, "element", { value: new JSDOM().window.document.body });
        Object.defineProperty(sheet, "rendered", { value: true });
        sheet.element.innerHTML =
            '<section data-tab="effects"><ol class="effects-list"><li class="effect-card" data-effect-id="created"></li></ol></section>';
        const row = sheet.element.querySelector("li")!;
        const animate = sandbox.stub();
        sandbox.define(row, "scrollIntoView", sandbox.stub());
        sandbox.define(row, "animate", animate);
        const changeTab = sandbox.stub(sheet, "changeTab");
        const render = sandbox.spy(sheet, "render");
        const effect = sandbox.createStubInstance(SplittermondActiveEffect);
        effect.type = type;
        effect.toObject = sandbox.stub<[source?: boolean], { type: string }>().returns({ type });
        const created = sandbox.createStubInstance(SplittermondActiveEffect);
        Object.defineProperty(created, "id", { value: "created" });
        const inheritedDrop = sandbox.stub(SplittermondItemSheet.prototype, "_onDropActiveEffect").resolves(created);
        const createEmbeddedDocuments = sandbox
            .stub<
                Parameters<SplittermondItem["createEmbeddedDocuments"]>,
                ReturnType<SplittermondItem["createEmbeddedDocuments"]>
            >()
            .resolves([created]);
        item.createEmbeddedDocuments = createEmbeddedDocuments;
        return { sheet, effect, created, changeTab, animate, render, inheritedDrop, createEmbeddedDocuments };
    }

    for (const type of effectTypes) {
        it(`reveals a successfully dropped ${type} effect`, async () => {
            const { sheet, effect, created, changeTab, animate, render, inheritedDrop, createEmbeddedDocuments } =
                prepareDrop(type);

            expect(await sheet._onDropActiveEffect(new Event("drop") as DragEvent, effect)).to.equal(created);

            expect(changeTab.callCount).to.equal(1);
            expect(changeTab.firstCall.args).to.deep.equal(["effects", "primary", { force: true }]);
            expect(animate.callCount).to.equal(1);
            expect(render.called, "Document changes already request the sheet render").to.be.false;
            expect(inheritedDrop.called).to.equal(type === "modifier");
            if (type === "autoGenerated") {
                expect(createEmbeddedDocuments.firstCall.args[1]).to.deep.equal([{ type: "modifier" }]);
            }
        });

        it(`preserves the tab when a ${type} effect drop fails`, async () => {
            const { sheet, effect, changeTab, animate, render, inheritedDrop, createEmbeddedDocuments } =
                prepareDrop(type);
            inheritedDrop.resolves(null);
            createEmbeddedDocuments.resolves([]);

            expect(await sheet._onDropActiveEffect(new Event("drop") as DragEvent, effect)).to.be.null;

            expect(changeTab.called, "An unsuccessful drop must not change tabs").to.be.false;
            expect(animate.called, "An unsuccessful drop must not highlight a row").to.be.false;
            expect(render.called, "An unsuccessful drop must not request a render").to.be.false;
            expect(inheritedDrop.called).to.equal(type === "modifier");
            if (type === "autoGenerated") {
                expect(createEmbeddedDocuments.firstCall.args[1]).to.deep.equal([{ type: "modifier" }]);
            }
        });
    }
});
