import type { QuenchBatchContext } from "@ethaks/fvtt-quench";
import { foundryApi } from "module/api/foundryApi";
import { withActor } from "../fixtures";
import { passesEventually } from "../../util";

export function fearConditionTest(context: QuenchBatchContext) {
    const { describe, it, expect } = context;

    describe("Angsterfüllt roll type restriction", function () {
        this.timeout(10000);

        ["compendium", "generated", "legacy"].forEach((source) => {
            it(
                `should only enforce safety rolls at nonzero levels with ${source} modifiers`,
                withActor(async (actor) => {
                    const compendiumItem =
                        source === "compendium"
                            ? await foundryApi.utils.fromUUID(
                                  "Compendium.splittermond.statuseffects.Item.gzmLLIA2iubCUVUD"
                              )
                            : null;
                    if (source === "compendium" && !compendiumItem) {
                        throw new Error("Angsterfüllt compendium item not found");
                    }
                    const [item] = await actor.createEmbeddedDocuments("Item", [
                        compendiumItem
                            ? compendiumItem.toObject()
                            : {
                                  type: "statuseffect",
                                  name: "Angsterfüllt",
                                  system: { level: 1, modifier: 'check.require rollType="safety"' },
                              },
                    ]);

                    if (source !== "compendium") {
                        await passesEventually(() => {
                            expect(item.effects.some((effect) => effect.type === "autoGenerated")).to.be.true;
                        });
                    }
                    if (source === "legacy") {
                        await item.deleteEmbeddedDocuments(
                            "ActiveEffect",
                            item.effects.map((effect) => effect.id)
                        );
                    }

                    for (const level of [1, 0, 1]) {
                        await item.update({ "system.level": level });

                        const check = await actor.skills.acrobatics.finalizeCheckInputData(
                            [],
                            undefined,
                            undefined,
                            undefined,
                            undefined,
                            "risk",
                            "skill",
                            false
                        );

                        expect(check?.rollType, `roll type at level ${level}`).to.equal(
                            level === 0 ? "risk" : "safety"
                        );
                        expect(actor.modifier.getForId("check.require").getModifiers().length).to.equal(
                            level === 0 ? 0 : 1
                        );
                        if (source === "legacy") {
                            expect(item.effects.size, "level updates keep the legacy modifier path").to.equal(0);
                        }
                    }
                })
            );
        });
    });
}
