import { QuenchBatchContext } from "@ethaks/fvtt-quench";
import { SplittermondActiveEffect } from "module/activeEffect";
import { regenerateBakedMultiplierEffects } from "module/activeEffect/migrations/regenerateBakedMultiplierEffects";
import { evaluate, of, times } from "module/modifiers/expressions/scalar";
import { serialize } from "module/modifiers/expressions/scalar/serialization";
import { foundryApi } from "module/api/foundryApi";
import { createItemFixture, withActor } from "../fixtures";
import { passesEventually } from "../../util";

const MIGRATION_FLAG_SCOPE = "splittermond";
const MIGRATION_FLAG_KEY = "bakedMultiplierV1MigrationDone";

function oldBakedSerializedValue() {
    return serialize(times(of(3), of(2)));
}

function serializedValueOf(effect: SplittermondActiveEffect): unknown {
    const system = effect.system as { modifiers?: Array<{ serializedValue?: unknown }> };
    return system.modifiers?.[0]?.serializedValue;
}

export function bakedMultiplierMigrationTest(context: QuenchBatchContext) {
    const { describe, it, expect, beforeEach, afterEach } = context;

    describe("regenerateBakedMultiplierEffects migration", () => {
        let originalMigrationFlag: unknown;
        beforeEach(() => {
            originalMigrationFlag = foundryApi.settings.get(MIGRATION_FLAG_SCOPE, MIGRATION_FLAG_KEY);
        });
        afterEach(async () => {
            await foundryApi.settings.set(MIGRATION_FLAG_SCOPE, MIGRATION_FLAG_KEY, originalMigrationFlag);
        });

        for (const migrationDone of [false, true])
            it(
                `regenerates only the selected documents and preserves the world migration flag (${migrationDone})`,
                withActor(async (actor) => {
                    await foundryApi.settings.set(MIGRATION_FLAG_SCOPE, MIGRATION_FLAG_KEY, migrationDone);

                    await using unselected = await createItemFixture({ type: "strength", name: "Unselected strength" });
                    const [unselectedEffect] = await unselected.item.createEmbeddedDocuments("ActiveEffect", [
                        {
                            name: "Unselected baked effect",
                            type: "autoGenerated",
                            system: {
                                modifiers: [{ path: "bonuscap", serializedValue: oldBakedSerializedValue() }],
                                costModifiers: [],
                            },
                        },
                    ]);
                    const originalUnselectedEffect = unselectedEffect.toObject();

                    const [item] = await actor.createEmbeddedDocuments("Item", [
                        {
                            type: "strength",
                            name: "Starker Zaubertrank",
                            system: { modifier: "bonuscap +2", quantity: 3 },
                        },
                    ]);

                    await passesEventually(
                        () => {
                            expect(
                                item.effects.filter((e: { type: string }) => e.type === "autoGenerated").length
                            ).to.be.greaterThan(0);
                        },
                        1500,
                        50
                    );

                    const effect = item.effects.find(
                        (e: { type: string }) => e.type === "autoGenerated"
                    ) as SplittermondActiveEffect;

                    expect(effect, "auto-generated effect should exist").to.not.be.undefined;
                    expect(await evaluate(effect.asModifiers[0].value), "pre-migration evaluates to 6").to.equal(6);

                    await effect.update({
                        system: {
                            modifiers: [
                                {
                                    ...(effect.system as { modifiers: object[] }).modifiers[0],
                                    serializedValue: oldBakedSerializedValue(),
                                },
                            ],
                        },
                    });

                    await passesEventually(
                        () => {
                            expect(JSON.stringify(serializedValueOf(effect))).to.equal(
                                JSON.stringify(oldBakedSerializedValue())
                            );
                        },
                        1500,
                        50
                    );
                    expect(
                        await evaluate(effect.asModifiers[0].value),
                        "baked-in value double-counts the multiplier under late evaluation (3 baked * 3 read-time = 18)"
                    ).to.equal(18);

                    await regenerateBakedMultiplierEffects({ actors: [actor], items: [] });

                    await passesEventually(
                        () => {
                            const e = item.effects.find((ef: { type: string }) => ef.type === "autoGenerated") as
                                SplittermondActiveEffect | undefined;
                            expect(e, "migrated auto-generated effect should exist").to.not.be.undefined;
                            expect(JSON.stringify(serializedValueOf(e!))).to.equal(JSON.stringify(serialize(of(2))));
                        },
                        1500,
                        50
                    );

                    const migratedEffect = item.effects.find(
                        (ef: { type: string }) => ef.type === "autoGenerated"
                    ) as SplittermondActiveEffect;

                    expect(migratedEffect.multiplier, "multiplier is still 3 at read time").to.equal(3);
                    expect(
                        await evaluate(migratedEffect.asModifiers[0].value),
                        "post-migration evaluates to 6"
                    ).to.equal(6);
                    expect(
                        unselected.item.effects.get(unselectedEffect.id)?.toObject(),
                        "unselected world items are untouched"
                    ).to.deep.equal(originalUnselectedEffect);
                    expect(
                        foundryApi.settings.get(MIGRATION_FLAG_SCOPE, MIGRATION_FLAG_KEY),
                        "a subset does not mark the whole world as migrated"
                    ).to.equal(migrationDone);
                })
            );
    });
}
