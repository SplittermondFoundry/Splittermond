import type { ModifierType } from "module/modifiers";
import type { ICostModifier } from "module/util/costs/spellCostManagement";
import type SplittermondItem from "module/item/item";
import type { IModifierSource } from "module/modifiers/IModifierSource";
import type { AddModifierResult, TaggedModifier } from "module/modifiers/modifierAddition";
import type { EffectType } from "module/activeEffect/dataModel/effectTypes";
import { serialize } from "module/modifiers/expressions/scalar/serialization";
import { CostModifierDataModel } from "./dataModel/CostModifierDataModel";
import type { SplittermondActiveEffect } from "module/activeEffect/SplittermondActiveEffect";
import { buildPropertyDerivedEffectData } from "./propertyEffectBuilder";

type AddModifierFn = (item: IModifierSource, str: string, type: ModifierType) => AddModifierResult;

interface HasModifierString {
    system: { modifier: string | null };
}

/**
 * Write-side sibling of `EffectDataObject` in `./types` (the read-side projection of
 * `ActiveEffect.toObject()`). The two are paired: builders construct `EffectCreationData`
 * for `createEmbeddedDocuments`, and readers/hook handlers consume `EffectDataObject`
 * from `toObject()` / substitutors. `system` is left as `object` because the narrowed
 * entry shapes (e.g. `propertyEffectBuilder`'s `attributes: { type: "equipment" }`)
 * are erased at the write boundary and re-derived by the DataModel on read.
 */
export interface EffectCreationData {
    name: string;
    origin: string;
    type: EffectType;
    transfer: boolean;
    disabled: boolean;
    system: object;
    flags: Record<string, unknown>;
}

function assembleEffectData(system: object, origin: string, rawFragment: string, type: EffectType): EffectCreationData {
    return {
        name: rawFragment,
        origin,
        type,
        transfer: true,
        disabled: false,
        system,
        flags: {
            splittermond: {
                rawInput: rawFragment,
            },
        },
    };
}

export function buildScalarEffectData(
    tagged: TaggedModifier[],
    origin: string,
    rawFragment: string,
    type: EffectType = "autoGenerated"
): EffectCreationData {
    const system = {
        modifiers: tagged.map((m) => ({
            path: m.modifier.groupId,
            serializedValue: serialize(m.modifier.value),
            implementation: m.implementation,
            selectable: m.modifier.selectable,
            attributes: m.modifier.attributes,
        })),
        costModifiers: [],
    };
    return assembleEffectData(system, origin, rawFragment, type);
}

function groupByRawFragment(modifiers: TaggedModifier[]): { rawFragment: string; tagged: TaggedModifier[] }[] {
    const groups = new Map<string, TaggedModifier[]>();
    for (const tagged of modifiers) {
        let group = groups.get(tagged.rawFragment);
        if (!group) {
            group = [];
            groups.set(tagged.rawFragment, group);
        }
        group.push(tagged);
    }
    return [...groups.entries()].map(([rawFragment, tagged]) => ({ rawFragment, tagged }));
}

export function buildCostEffectData(
    modifier: ICostModifier,
    rawFragment: string,
    origin: string,
    type: EffectType = "autoGenerated"
): EffectCreationData {
    const costModifierEntry = CostModifierDataModel.init(
        modifier.label,
        modifier.value,
        modifier.skill,
        modifier.attributes
    );
    const system = {
        modifiers: [],
        costModifiers: [costModifierEntry],
    };
    return assembleEffectData(system, origin, rawFragment, type);
}

function effectDataFromAddResult(
    addModifier: AddModifierFn,
    item: IModifierSource,
    modifierString: string,
    modifierType: ModifierType,
    type: EffectType
): EffectCreationData[] {
    const { modifiers, costModifiers } = addModifier(item, modifierString, modifierType);
    const grouped = groupByRawFragment(modifiers);
    return [
        ...grouped.map(({ tagged, rawFragment }) => buildScalarEffectData(tagged, item.uuid, rawFragment, type)),
        ...costModifiers.map(({ modifier, rawFragment }) =>
            buildCostEffectData(modifier, rawFragment, item.uuid, type)
        ),
    ];
}

/**
 * Add ActiveEffects from a modifier string to an item, without deleting existing effects.
 */
export async function addModifierEffects(
    addModifier: AddModifierFn,
    item: IModifierSource,
    modifierString: string,
    modifierType: ModifierType = "innate",
    type: EffectType = "autoGenerated"
): Promise<SplittermondActiveEffect[] | void> {
    if (!modifierString.trim()) return;

    const effectDataArray = effectDataFromAddResult(addModifier, item, modifierString, modifierType, type);

    if (effectDataArray.length > 0) {
        return (
            item as unknown as { createEmbeddedDocuments(t: string, d: object[]): Promise<SplittermondActiveEffect[]> }
        ).createEmbeddedDocuments("ActiveEffect", effectDataArray);
    }
}

export function isGenerated(effect: { type: string }): boolean {
    return effect.type === "autoGenerated";
}

/**
 * Rebuild the auto-generated ActiveEffects on an item from its modifier string.
 * Deletes existing auto-generated effects, then creates new ones from the current string.
 *
 * If `modifierString` is omitted, the item's `system.modifier` field is used. Callers that
 * need to substitute template placeholders (e.g. masteries' `${skill}`/`${name}`) must pass
 * the already-substituted string explicitly.
 */
export async function rebuildModifierEffects(
    addModifier: AddModifierFn,
    item: SplittermondItem,
    modifierType: ModifierType,
    modifierString?: string
): Promise<void> {
    const resolvedModifierString: string = modifierString ?? (item as HasModifierString).system.modifier ?? "";

    const existingAutoEffects = item.effects.filter(isGenerated);
    const idsToDelete: string[] = existingAutoEffects.map((e) => e.id);
    if (idsToDelete.length > 0) {
        await item.deleteEmbeddedDocuments("ActiveEffect", idsToDelete);
    }

    const effectDataArray: EffectCreationData[] = [];

    if (resolvedModifierString.trim()) {
        effectDataArray.push(
            ...effectDataFromAddResult(addModifier, item, resolvedModifierString, modifierType, "autoGenerated")
        );
    }

    const propertyEffect = buildPropertyDerivedEffectData(item);
    if (propertyEffect) effectDataArray.push(propertyEffect);

    if (effectDataArray.length > 0) {
        await item.createEmbeddedDocuments("ActiveEffect", effectDataArray);
    }
}
